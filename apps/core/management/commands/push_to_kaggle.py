EXPORT_QUERIES = {

    'funds.csv': """
        SELECT
            s.amfi_code,
            s.isin_growth,
            s.isin_idcw,
            s.scheme_name,
            s.fund_house,
            s.scheme_type,
            s.scheme_category,
            s.plan,
            s.is_direct,
            s.is_etf,
            s.is_active,
            s.expense_ratio,
            s.aum_cr,
            s.nav_latest,
            s.nav_date,
            s.morningstar_id,
            s.yahoo_ticker
        FROM funds_scheme s
        WHERE s.is_active = true
        ORDER BY s.amfi_code
    """,

    'fund_screener.csv': """
        SELECT
            s.amfi_code,
            s.scheme_name,
            s.fund_house,
            s.scheme_category,
            s.is_etf,
            snap.expense_ratio,
            snap.aum_cr,
            snap.returns_1m_pct,
            snap.returns_3m_pct,
            snap.returns_6m_pct,
            snap.returns_1y_pct,
            snap.returns_3y_pct,
            snap.returns_5y_pct,
            snap.cagr_3y_pct,
            snap.cagr_7y_pct,
            snap.cagr_10y_pct,
            snap.cagr_si_pct,
            snap.rolling_return_3y_pct,
            snap.rolling_return_5y_pct,
            snap.volatility_1y_pct,
            snap.volatility_3y_pct,
            snap.volatility_5y_pct,
            snap.sharpe_ratio,
            snap.sortino_ratio,
            snap.max_drawdown,
            snap.alpha_3y,
            snap.beta_3y,
            snap.info_ratio_3y,
            snap.updated_at
        FROM funds_fundscreenersnapshot snap
        JOIN funds_scheme s ON s.id = snap.scheme_id
        ORDER BY s.amfi_code
    """,

    'fund_scores.csv': """
        SELECT
            s.amfi_code,
            ms.score_version,
            ms.final_score,
            ms.confidence,
            ms.score_badge,
            ms.score_performance,
            ms.score_risk,
            ms.score_cost,
            ms.score_composition,
            ms.score_debt,
            ms.score_manager,
            ms.updated_at
        FROM funds_fundmodelscore ms
        JOIN funds_scheme s ON s.id = ms.scheme_id
        ORDER BY s.amfi_code
    """,

    'nav_history.csv': """
        SELECT
            s.amfi_code,
            n.date,
            n.nav
        FROM funds_navhistory n
        JOIN funds_scheme s ON s.id = n.scheme_id
        ORDER BY s.amfi_code, n.date
    """,

    'benchmarks.csv': """
        SELECT
            bi.name AS benchmark_name,
            bi.yahoo_ticker,
            bn.date,
            bn.close,
            bn.source
        FROM benchmarks_benchmarkindex bi
        JOIN benchmarks_benchmarknav bn ON bn.index_id = bi.id
        ORDER BY bi.name, bn.date
    """,

    'benchmark_returns.csv': """
        SELECT
            bi.name AS benchmark_name,
            br.ret_1w,
            br.ret_1m,
            br.ret_3m,
            br.ret_6m,
            br.ret_ytd,
            br.ret_1y,
            br.ret_3y,
            br.ret_5y,
            br.ret_10y,
            br.ret_since_launch,
            br.volatility_1y,
            br.volatility_3y,
            br.volatility_5y,
            br.updated_at
        FROM benchmarks_benchmarkindex bi
        JOIN benchmarks_benchmarkreturns br ON br.index_id = bi.id
        ORDER BY bi.name
    """,

    'trailing_returns.csv': """
        SELECT
            s.amfi_code,
            tr.period,
            tr.years,
            tr.cagr_pct,
            tr.bm_cagr,
            tr.excess,
            tr.as_of
        FROM analytics_trailingreturn tr
        JOIN funds_scheme s ON s.id = tr.scheme_id
        ORDER BY s.amfi_code, tr.years
    """,

    'risk_metrics.csv': """
        SELECT
            s.amfi_code,
            rm.period,
            rm.period_days,
            rm.std_dev_ann AS volatility,
            rm.sharpe_ratio,
            rm.sortino_ratio,
            rm.max_drawdown,
            rm.beta,
            rm.alpha_ann AS alpha,
            rm.r_squared,
            rm.info_ratio,
            rm.as_of
        FROM analytics_riskmetrics rm
        JOIN funds_scheme s ON s.id = rm.scheme_id
        ORDER BY s.amfi_code, rm.period
    """,
}


