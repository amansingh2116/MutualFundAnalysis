def _kaggle_username() -> str:
    """Return Kaggle username from env or ~/.kaggle/kaggle.json."""
    username = os.environ.get('KAGGLE_USERNAME', '')
    if not username:
        cfg = Path.home() / '.kaggle' / 'kaggle.json'
        if cfg.exists():
            with open(cfg) as f:
                username = json.load(f).get('username', '')
    return username


def _run_kaggle(args: list[str], cwd: str) -> str:
    """Run a kaggle CLI command, raising CommandError on failure."""
    cmd = [sys.executable, '-m', 'kaggle'] + args
    result = subprocess.run(cmd, cwd=cwd, capture_output=True, text=True)
    if result.returncode != 0:
        raise CommandError(
            f"kaggle command failed:\n{result.stdout}\n{result.stderr}"
        )
    return result.stdout


def _export_table_to_csv(sql: str, filepath: str, stdout) -> int:
    """Execute SQL and write results to CSV. Returns row count."""
    with connection.cursor() as cur:
        cur.execute(sql)
        columns = [col[0] for col in cur.description]
        with open(filepath, 'w', newline='', encoding='utf-8') as f:
            writer = csv.writer(f)
            writer.writerow(columns)
            rows = 0
            while True:
                batch = cur.fetchmany(10_000)
                if not batch:
                    break
                writer.writerows(batch)
                rows += len(batch)
                if rows % 100_000 == 0:
                    stdout.write(f"\r    {rows:,} rows...", ending='')
                    stdout.flush()
    return rows


