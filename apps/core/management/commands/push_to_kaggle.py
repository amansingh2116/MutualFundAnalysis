class Command(BaseCommand):
    help = 'Export database to CSV and push to Kaggle as a dataset'

    def add_arguments(self, parser):
        parser.add_argument(
            '--create',
            action='store_true',
            help='Create a brand-new dataset (first time only). Omit for subsequent version updates.',
        )
        parser.add_argument(
            '--message', '-m',
            default=f"Data refresh -- {date.today().strftime('%B %Y')}",
            help='Version message for this Kaggle update.',
        )
        parser.add_argument(
            '--skip-nav',
            action='store_true',
            help='Skip exporting nav_history.csv (large file, ~600 MB). Use for fast metadata-only updates.',
        )
        parser.add_argument(
            '--output-dir',
            default=None,
            help='Directory to write CSV exports (default: system temp dir, cleaned up after push).',
        )
        parser.add_argument(
            '--dry-run',
            action='store_true',
            help='Export CSVs only -- do not push to Kaggle.',
        )
        parser.add_argument(
            '--slug',
            default='indian-mutual-funds-complete-nav-analytics',
            help='Kaggle dataset slug (used in the dataset URL).',
        )

    def handle(self, *args, **options):
        create   = options['create']
        message  = options['message']
        skip_nav = options['skip_nav']
        dry_run  = options['dry_run']
        slug     = options['slug']

        username = _kaggle_username()
        if not username and not dry_run:
            raise CommandError(
                "Kaggle username not found. Set KAGGLE_USERNAME env var or "
                "create ~/.kaggle/kaggle.json via: kaggle datasets list"
            )

        # Resolve export directory
        use_temp = options['output_dir'] is None
        export_dir = Path(options['output_dir']) if options['output_dir'] else Path(tempfile.mkdtemp())
        export_dir.mkdir(parents=True, exist_ok=True)

        self.stdout.write(self.style.MIGRATE_HEADING(
            f"\nMutualFundAnalysis -- Kaggle Dataset Export"
            f"\n  Target:    {username}/{slug}"
            f"\n  Export to: {export_dir}"
            f"\n  Mode:      {'CREATE new dataset' if create else 'UPDATE existing version'}"
            f"\n  Dry run:   {dry_run}\n"
        ))

        try:
            # ── Export CSVs ────────────────────────────────────────────────
            total_rows = 0
            queries = dict(EXPORT_QUERIES)

            if skip_nav:
                queries.pop('nav_history.csv', None)
                self.stdout.write("  [skip] nav_history.csv (--skip-nav flag set)")

            for filename, sql in queries.items():
                filepath = str(export_dir / filename)
                self.stdout.write(f"  Exporting {filename}...", ending='')
                self.stdout.flush()
                try:
                    rows = _export_table_to_csv(sql, filepath, self.stdout)
                    total_rows += rows
                    size_mb = os.path.getsize(filepath) / (1024 * 1024)
                    self.stdout.write(f"\r  [OK] {filename:<30} {rows:>10,} rows  ({size_mb:.1f} MB)")
                except Exception as e:
                    self.stdout.write(self.style.WARNING(f"\r  [WARN] {filename} -- skipped: {e}"))

            # ── Write README.md ────────────────────────────────────────────
            readme_content = _generate_readme()
            readme_path = export_dir / 'README.md'
            readme_path.write_text(readme_content, encoding='utf-8')
            self.stdout.write(f"\n  [OK] README.md written (Last Updated: {date.today().strftime('%d %B %Y')})")

            # ── Write dataset-metadata.json ────────────────────────────────
            meta = {
                "title":       DATASET_TITLE,
                "id":          f"{username}/{slug}",
                "licenses":    DATASET_LICENSES,
                "subtitle":    DATASET_SUBTITLE,
                "description": readme_content,
                "keywords": [
                    "mutual funds", "india", "finance", "investment",
                    "nifty", "nav", "amfi", "sebi", "etf"
                ],
                "collaborators": [],
                "data": [
                    {
                        "description": "",
                        "name": f,
                        "totalBytes": os.path.getsize(str(export_dir / f))
                    }
                    for f in sorted(os.listdir(str(export_dir)))
                    if f.endswith('.csv')
                ],
            }
            meta_path = export_dir / 'dataset-metadata.json'
            meta_path.write_text(json.dumps(meta, indent=2), encoding='utf-8')
            self.stdout.write(f"  [OK] dataset-metadata.json written")

            self.stdout.write(self.style.SUCCESS(
                f"\n  Export complete: {total_rows:,} total rows across {len(queries)} files"
            ))

            if dry_run:
                self.stdout.write(self.style.WARNING(
                    f"\nDRY RUN -- files saved to: {export_dir}\n"
                    f"Re-run without --dry-run to push to Kaggle."
                ))
                return

            # ── Push to Kaggle ─────────────────────────────────────────────
            self.stdout.write(f"\nPushing to Kaggle as {username}/{slug}...")

            if create:
                self.stdout.write("  Creating new dataset (first time)...")
                _run_kaggle(
                    ['datasets', 'create', '-p', str(export_dir), '--dir-mode', 'zip'],
                    cwd=str(export_dir)
                )
            else:
                self.stdout.write(f"  Publishing new version: '{message}'...")
                _run_kaggle(
                    ['datasets', 'version', '-p', str(export_dir),
                     '-m', message, '--dir-mode', 'zip'],
                    cwd=str(export_dir)
                )

            self.stdout.write(self.style.SUCCESS(
                f"\nDataset published: https://www.kaggle.com/datasets/{username}/{slug}\n"
            ))

        finally:
            if use_temp and not dry_run:
                shutil.rmtree(str(export_dir), ignore_errors=True)
